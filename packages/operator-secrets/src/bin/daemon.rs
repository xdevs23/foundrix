//! operator-secretsd — collects the operator-provided secrets a host
//! cannot generate for itself, and releases the boot once every one of
//! them is present and PROVEN valid.
//!
//! Runs as a oneshot systemd unit ordered before its consumers: exiting 0
//! releases the boot, and the deliberate undecided state simply never
//! exits. UI state is served to TUI clients over a unix socket so the
//! console and any SSH session share one screen.
//!
//! Secret values live in this process's memory, on the validator's stdin
//! and in the destination file — nowhere else. They are never passed in
//! argv or the environment, never logged, never put in a snapshot (which
//! goes to every connected client), and never written to the nix store.

use std::collections::BTreeMap;
use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::Mutex;
use std::time::Duration;

use anyhow::{Context, Result, bail};
use clap::Parser;
use tokio::io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader};
use tokio::net::{UnixListener, UnixStream};
use tokio::process::Command;
use tokio::sync::{mpsc, watch};

use operator_secrets::{
    ClientMsg, Prompt, SOCKET_PATH, SecretSpec, SecretState, SecretStatus, Snapshot, Spec,
    StoredState, ValidatorRequest, ValidatorStatus, Verdict, accept_submission, classify_stored,
    encode_env_file, lookup_id, parse_env_file, parse_mode, parse_validator_output, prompt_fields,
    state_file_for,
};

#[derive(Parser)]
#[command(about = "Collect and validate operator-provided secrets before the boot proceeds")]
struct Cli {
    /// Spec JSON generated by services/operator-secrets.nix. Contains no
    /// secret values, only identity — hence safe in the nix store.
    #[arg(long)]
    spec: PathBuf,

    /// Control socket TUI clients connect to.
    #[arg(long, default_value = SOCKET_PATH)]
    socket: PathBuf,

    /// Hard limit on a single validator run. A validator that hangs is
    /// `error` (cannot decide), never `invalid`.
    #[arg(long, default_value_t = 60)]
    validator_timeout_secs: u64,

    /// How often to re-run a validator that could not decide. The boot
    /// stays parked meanwhile; nothing is written or discarded.
    #[arg(long, default_value_t = 30)]
    retry_interval_secs: u64,
}

// --- UI hub -----------------------------------------------------------------

struct Ui {
    state_file: PathBuf,
    snapshot: Mutex<Snapshot>,
    tx: watch::Sender<Snapshot>,
    submissions: Mutex<mpsc::UnboundedReceiver<ClientMsg>>,
    next_prompt_id: Mutex<u64>,
}

impl Ui {
    fn mutate(&self, f: impl FnOnce(&mut Snapshot)) {
        let mut snap = self.snapshot.lock().unwrap();
        f(&mut snap);
        // The state file is the breadcrumb for `ssh host 'cat ...'`
        // scripting and for a TUI that connects after the daemon is gone.
        // It carries the message line only — which never holds a value.
        let _ = std::fs::write(&self.state_file, format!("{}\n", snap.message));
        let _ = self.tx.send(snap.clone());
    }

    /// Set the headline. Also goes to stderr (the journal) — so it must
    /// never be built from a field value.
    fn state(&self, phase: &str, message: impl Into<String>) {
        let message = message.into();
        eprintln!("operator-secrets: {message}");
        self.mutate(|s| {
            s.phase = phase.into();
            s.message = message;
        });
    }

    fn set_secret(&self, name: &str, state: SecretState, detail: impl Into<String>) {
        let detail = detail.into();
        self.mutate(|s| {
            if let Some(e) = s.secrets.iter_mut().find(|e| e.name == name) {
                e.state = state;
                e.detail = detail;
            }
        });
    }

    fn blocked(&self, blocked: bool) {
        self.mutate(|s| s.blocked = blocked);
    }

    /// Post a form and wait for the first complete answer from any client.
    /// Rejected answers re-prompt rather than failing the boot; a typo at
    /// 3am must not mean a power-cycle.
    async fn ask(
        &self,
        spec: &SecretSpec,
        reason: &str,
        known: &BTreeMap<String, String>,
    ) -> Vec<(String, String)> {
        let mut known = known.clone();
        let mut reason = reason.to_string();
        loop {
            let id = {
                let mut n = self.next_prompt_id.lock().unwrap();
                *n += 1;
                *n
            };
            let prompt = Prompt {
                id,
                secret: spec.name.clone(),
                description: spec.description.clone(),
                reason: reason.clone(),
                fields: prompt_fields(spec, &known),
            };
            self.mutate(|s| s.prompt = Some(prompt));

            let values = self.wait_for_submission(id).await;
            self.mutate(|s| s.prompt = None);

            match accept_submission(spec, &values) {
                Ok(v) => return v,
                Err(e) => {
                    // Keep the operator's non-sensitive typing; drop the
                    // rest. `e` names a field, never a value.
                    known = values
                        .into_iter()
                        .filter(|(k, _)| spec.field(k).is_some_and(|f| !f.sensitive))
                        .collect();
                    reason = format!("rejected: {e}");
                    self.state("prompt", format!("{}: submission {reason}", spec.name));
                }
            }
        }
    }

    async fn wait_for_submission(&self, id: u64) -> Vec<(String, String)> {
        loop {
            let msg = {
                let mut rx = self.submissions.lock().unwrap();
                rx.try_recv().ok()
            };
            match msg {
                Some(ClientMsg::Submit { prompt_id, values }) if prompt_id == id => return values,
                // Stale answer to an older prompt (a client that had not
                // yet seen the new one): ignore.
                Some(_) => continue,
                None => tokio::time::sleep(Duration::from_millis(100)).await,
            }
        }
    }
}

// --- validator --------------------------------------------------------------

/// Run the validator for one secret.
///
/// The values go in over stdin as one JSON object and nowhere else: not
/// argv (world-readable in /proc/<pid>/cmdline), not the environment
/// (inherited by children, readable in /proc/<pid>/environ). The
/// environment IS inherited so the validator can find its TLS trust store,
/// but it carries nothing of ours.
///
/// The exit code is deliberately ignored: `status` on stdout is
/// authoritative. Anything else — crash, timeout, no JSON, junk JSON — is
/// `error`, never `invalid`.
async fn validate(spec: &SecretSpec, values: &[(String, String)], timeout: Duration) -> Verdict {
    // A secret without a validator has no external proof; the acceptance
    // criterion is "every declared field present and non-empty". This is
    // decided here, in the same chokepoint as external validation, so the
    // stored-file and prompted-input paths cannot diverge.
    let Some(validate_command) = &spec.validate_command else {
        for f in &spec.fields {
            match values.iter().find(|(k, _)| k == &f.name) {
                Some((_, v)) if !v.is_empty() => {}
                _ => {
                    return Verdict::invalid(format!(
                        "field {} is missing or empty (no validator configured; all \
                         declared fields must be present and non-empty)",
                        f.name
                    ));
                }
            }
        }
        return Verdict::valid();
    };

    let request = ValidatorRequest {
        fields: values.iter().cloned().collect(),
    };
    let body = match serde_json::to_vec(&request) {
        Ok(b) => b,
        Err(e) => return Verdict::error(format!("serializing validator request: {e}")),
    };

    let mut child = match Command::new(&validate_command[0])
        .args(&validate_command[1..])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .kill_on_drop(true)
        .spawn()
    {
        Ok(c) => c,
        Err(e) => {
            return Verdict::error(format!("spawning validator {}: {e}", validate_command[0]));
        }
    };

    let mut stdin = match child.stdin.take() {
        Some(s) => s,
        None => return Verdict::error("validator has no stdin pipe"),
    };
    let mut stdout = child.stdout.take();
    let mut stderr = child.stderr.take();

    // Feed stdin and drain both output pipes CONCURRENTLY: a validator
    // that writes more than a pipe buffer before reading its input would
    // otherwise deadlock against us.
    let feed = async move {
        // A validator that exits without reading EPIPEs this write; its
        // own output is the diagnostic that matters, so the result is
        // dropped rather than reported.
        let _ = stdin.write_all(&body).await;
        drop(stdin); // EOF
    };
    async fn drain(r: Option<impl AsyncReadExt + Unpin>) -> String {
        let mut buf = Vec::new();
        if let Some(mut r) = r {
            let _ = r.read_to_end(&mut buf).await;
        }
        String::from_utf8_lossy(&buf).trim().to_string()
    }

    let work = async {
        let (_, out, err) = tokio::join!(feed, drain(stdout.take()), drain(stderr.take()));
        let status = child.wait().await;
        (out, err, status)
    };

    let (out, err, status) = match tokio::time::timeout(timeout, work).await {
        Ok(v) => v,
        Err(_) => {
            return Verdict::error(format!(
                "validator did not answer within {}s — cannot decide",
                timeout.as_secs()
            ));
        }
    };

    let mut verdict = parse_validator_output(&out);
    if verdict.status == ValidatorStatus::Error {
        // Attach what diagnostics we have. This is the validator's own
        // stderr and exit status, never our field values — a validator
        // that echoes its input to stderr is broken by the contract in
        // docs/operator-secrets.md.
        // Only worth showing when it is surprising: a validator that
        // exited cleanly and reported `error` itself has already said
        // everything useful in its message.
        let code = match &status {
            Ok(s) if s.success() => None,
            Ok(s) => Some(format!("{s}")),
            Err(e) => Some(format!("wait failed: {e}")),
        };
        let mut detail = match code {
            Some(c) => format!("{} ({c})", verdict.message),
            None => verdict.message.clone(),
        };
        if !err.is_empty() {
            // Redact before truncating, so a value split across the 400-char
            // boundary cannot survive as a fragment.
            let err = redact_values(&err, values);
            let mut e: String = err.chars().take(400).collect();
            if err.chars().count() > 400 {
                e.push('…');
            }
            detail.push_str(&format!("; stderr: {e}"));
        }
        verdict.message = detail;
    }
    verdict
}

/// Strip any field value that appears verbatim in text destined for the
/// journal and the state file.
///
/// The contract in docs/operator-secrets.md forbids a validator from
/// echoing its input, and the shipped one does not — this is the belt to
/// that braces. A third-party validator whose runtime prints a stack trace
/// containing the parsed request would otherwise put a secret in the
/// journal, which is exactly the place this mechanism promises it never
/// reaches. Values shorter than 4 characters are left alone: they carry
/// little and would turn ordinary diagnostics into confetti.
fn redact_values(text: &str, values: &[(String, String)]) -> String {
    let mut out = text.to_string();
    for (_, v) in values {
        if v.chars().count() >= 4 && out.contains(v.as_str()) {
            out = out.replace(v.as_str(), "«redacted»");
        }
    }
    out
}

// --- writing ----------------------------------------------------------------

struct Ids {
    uid: u32,
    gid: u32,
}

/// Resolve owner/group up front, before any prompting, so a typo in the
/// nix config fails the boot loudly instead of after the operator has
/// typed a secret in.
fn resolve_ids(spec: &SecretSpec) -> Result<Ids> {
    let passwd = read_db("/etc/passwd");
    let group = read_db("/etc/group");
    let uid = lookup_id(&passwd, &spec.owner)
        .or_else(|| getent("passwd", &spec.owner))
        .with_context(|| format!("secret {}: unknown owner {:?}", spec.name, spec.owner))?;
    let gid = lookup_id(&group, spec.group())
        .or_else(|| getent("group", spec.group()))
        .with_context(|| format!("secret {}: unknown group {:?}", spec.name, spec.group()))?;
    Ok(Ids { uid, gid })
}

fn read_db(path: &str) -> String {
    std::fs::read_to_string(path).unwrap_or_default()
}

/// NSS fallback for users that are not in the flat files.
fn getent(db: &str, name: &str) -> Option<u32> {
    let out = std::process::Command::new("getent")
        .args([db, name])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    lookup_id(&String::from_utf8_lossy(&out.stdout), name)
}

/// Write the env-file atomically, never world-readable at any instant.
///
/// The temp file is CREATED with 0600 (an explicit mode, so a permissive
/// umask cannot widen it), then chowned, then chmodded to the target
/// mode, and only then renamed into place. A reader therefore sees either
/// the old file or a complete, correctly-owned new one — never a
/// half-written or briefly-readable secret.
fn write_secret(spec: &SecretSpec, ids: &Ids, values: &[(String, String)]) -> Result<()> {
    let path = Path::new(&spec.path);
    let dir = path
        .parent()
        .context("secret path has no parent directory")?;
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;

    let mode = parse_mode(&spec.mode).context("invalid mode")?;
    let tmp = dir.join(format!(
        ".{}.tmp.{}",
        path.file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("secret"),
        std::process::id()
    ));
    let _ = std::fs::remove_file(&tmp);

    let body = encode_env_file(values);
    {
        use std::io::Write;
        let mut f = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o600)
            .open(&tmp)
            .with_context(|| format!("creating {}", tmp.display()))?;
        f.write_all(body.as_bytes()).context("writing secret")?;
        f.sync_all().context("syncing secret")?;
    }

    let cleanup = |e: anyhow::Error| {
        let _ = std::fs::remove_file(&tmp);
        e
    };
    std::os::unix::fs::chown(&tmp, Some(ids.uid), Some(ids.gid))
        .map_err(|e| cleanup(anyhow::anyhow!("chown {}: {e}", tmp.display())))?;
    std::fs::set_permissions(&tmp, PermissionsExt::from_mode(mode))
        .map_err(|e| cleanup(anyhow::anyhow!("chmod {}: {e}", tmp.display())))?;
    std::fs::rename(&tmp, path)
        .map_err(|e| cleanup(anyhow::anyhow!("rename into {}: {e}", path.display())))?;

    // Durability of the rename itself: without this the file can vanish
    // on a power cut and the next boot re-prompts. Best-effort.
    if let Ok(d) = std::fs::File::open(dir) {
        let _ = d.sync_all();
    }
    Ok(())
}

// --- per-secret state machine -----------------------------------------------

/// Validate, blocking (but never writing or discarding) for as long as the
/// validator cannot decide.
///
/// This is the `error` row of the state machine. A transient failure —
/// SSO down, network late — must never be mistaken for a wrong
/// credential, so we park here and keep asking rather than re-prompting
/// or rewriting. Recovery is automatic once the dependency comes back.
async fn validate_until_decided(
    ui: &Ui,
    spec: &SecretSpec,
    values: &[(String, String)],
    what: &str,
    timeout: Duration,
    retry: Duration,
) -> Verdict {
    let mut attempt: u32 = 0;
    loop {
        attempt += 1;
        ui.set_secret(
            &spec.name,
            SecretState::Validating,
            format!("validating {what}"),
        );
        let verdict = validate(spec, values, timeout).await;
        if verdict.status != ValidatorStatus::Error {
            if attempt > 1 {
                ui.blocked(false);
            }
            return verdict;
        }
        ui.set_secret(
            &spec.name,
            SecretState::Undecided,
            format!("validator cannot decide: {}", verdict.message),
        );
        ui.blocked(true);
        ui.state(
            "undecided",
            format!(
                "{}: validator cannot decide ({}); nothing written, nothing discarded — retrying in {}s (attempt {attempt})",
                spec.name,
                verdict.message,
                retry.as_secs()
            ),
        );
        tokio::time::sleep(retry).await;
    }
}

/// Bring one secret to the satisfied state.
async fn satisfy(
    ui: &Ui,
    spec: &SecretSpec,
    ids: &Ids,
    timeout: Duration,
    retry: Duration,
) -> Result<()> {
    ui.set_secret(&spec.name, SecretState::Checking, "reading stored file");
    ui.state(
        "check",
        format!("{}: checking stored credentials", spec.name),
    );

    // --- stored file ---
    let stored = match std::fs::read_to_string(&spec.path) {
        Ok(text) => Some(parse_env_file(&text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => bail!("reading {}: {e}", spec.path),
    };

    let mut known: BTreeMap<String, String> = BTreeMap::new();
    // Assigned by every branch below that does not return.
    let mut reason;

    match classify_stored(spec, stored.as_ref()) {
        StoredState::Absent => {
            reason = "no credentials stored yet".into();
            ui.state("prompt", format!("{}: not stored yet", spec.name));
        }
        StoredState::Incomplete { reason: r, usable } => {
            // Nothing coherent to validate: prompt straight away. `usable`
            // holds whatever parsed, which in a half-written file can
            // include a sensitive value whose sibling is missing — drop
            // those here, the same way both other branches build `known`.
            // prompt_fields() blanks sensitive pre-fills too, but the
            // discipline is to never carry a value further than needed
            // rather than to rely on a single downstream filter.
            known = usable
                .into_iter()
                .filter(|(k, _)| spec.field(k).is_some_and(|f| !f.sensitive))
                .collect();
            reason = r.clone();
            ui.state("prompt", format!("{}: {r}", spec.name));
        }
        StoredState::Complete(values) => {
            let verdict =
                validate_until_decided(ui, spec, &values, "stored credentials", timeout, retry)
                    .await;
            match verdict.status {
                ValidatorStatus::Valid => {
                    // Steady state: one request, no prompt, boot unattended.
                    ui.set_secret(
                        &spec.name,
                        SecretState::Satisfied,
                        "stored credentials valid",
                    );
                    ui.state("check", format!("{}: stored credentials valid", spec.name));
                    return Ok(());
                }
                ValidatorStatus::Invalid => {
                    // Self-healing prompt: the file stays on disk untouched
                    // until a replacement is proven good.
                    known = spec
                        .fields
                        .iter()
                        .filter(|f| !f.sensitive)
                        .filter_map(|f| {
                            values
                                .iter()
                                .find(|(k, _)| *k == f.name)
                                .map(|(k, v)| (k.clone(), v.clone()))
                        })
                        .collect();
                    reason = if verdict.message.is_empty() {
                        "stored credentials were rejected".into()
                    } else {
                        format!("stored credentials were rejected: {}", verdict.message)
                    };
                    ui.state("prompt", format!("{}: {reason}", spec.name));
                }
                ValidatorStatus::Error => {
                    unreachable!("validate_until_decided never returns error")
                }
            }
        }
    }

    // --- prompt loop ---
    loop {
        ui.set_secret(&spec.name, SecretState::NeedsInput, reason.clone());
        let values = ui.ask(spec, &reason, &known).await;

        let verdict =
            validate_until_decided(ui, spec, &values, "entered credentials", timeout, retry).await;
        match verdict.status {
            ValidatorStatus::Valid => {
                write_secret(spec, ids, &values)
                    .with_context(|| format!("writing {}", spec.path))?;
                ui.set_secret(&spec.name, SecretState::Satisfied, "accepted and written");
                ui.state(
                    "check",
                    format!("{}: accepted and written to {}", spec.name, spec.path),
                );
                return Ok(());
            }
            ValidatorStatus::Invalid => {
                known = values
                    .into_iter()
                    .filter(|(k, _)| spec.field(k).is_some_and(|f| !f.sensitive))
                    .collect();
                reason = if verdict.message.is_empty() {
                    "rejected by the validator".into()
                } else {
                    format!("rejected by the validator: {}", verdict.message)
                };
                ui.state("prompt", format!("{}: {reason}", spec.name));
            }
            ValidatorStatus::Error => unreachable!("validate_until_decided never returns error"),
        }
    }
}

// --- socket directory -------------------------------------------------------

/// Make the socket's parent directory private to root, refusing to take
/// over a directory that is not ours to lock down.
///
/// The socket must be unreachable by unprivileged users: anyone who can
/// connect can choose which credential the host ends up trusting. But
/// blindly chmodding the parent to 0700 is a foot-gun — `--socket
/// /run/x.sock` would lock down `/run` itself and cut every non-root
/// service off from dbus, postgres sockets and the rest, wedging the boot
/// with no obvious cause.
///
/// So: create the directory ourselves with an explicit 0700 (never
/// widened by a permissive umask), and if it already exists, accept it
/// only when it is ALREADY root-owned and inaccessible to group/other. A
/// pre-existing shared directory is refused loudly instead of being
/// silently narrowed — the config is wrong and the operator needs to know,
/// not to debug a half-dead boot.
fn prepare_socket_dir(dir: &Path) -> Result<()> {
    use std::fs::DirBuilder;
    use std::os::unix::fs::DirBuilderExt;

    if let Some(parent) = dir.parent() {
        // Intermediates only; the leaf is created with an explicit mode.
        std::fs::create_dir_all(parent)
            .with_context(|| format!("creating {}", parent.display()))?;
    }

    match DirBuilder::new().mode(0o700).create(dir) {
        Ok(()) => return Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
        Err(e) => bail!("creating {}: {e}", dir.display()),
    }

    let meta = std::fs::metadata(dir).with_context(|| format!("stat {}", dir.display()))?;
    if !meta.is_dir() {
        bail!("{} exists and is not a directory", dir.display());
    }
    use std::os::unix::fs::MetadataExt;
    let mode = meta.permissions().mode() & 0o777;
    // "Private to the daemon's owner": owned by the uid this process runs as
    // (root in production, but not necessarily under `cargo test`, where the
    // build user owns temp dirs) and inaccessible to group/other.
    let euid = unsafe { libc::geteuid() };
    if meta.uid() != euid || mode & 0o077 != 0 {
        bail!(
            "{} already exists and is not private to this daemon's owner \
             (owned by uid {}, we are uid {}, mode {:04o}); refusing to \
             narrow a directory this daemon does not own — point --socket \
             at a dedicated directory instead",
            dir.display(),
            meta.uid(),
            euid,
            mode
        );
    }
    Ok(())
}

// --- socket server ----------------------------------------------------------

async fn serve_client(
    stream: UnixStream,
    mut rx: watch::Receiver<Snapshot>,
    tx_submit: mpsc::UnboundedSender<ClientMsg>,
) {
    let (read_half, mut write_half) = stream.into_split();
    let mut lines = BufReader::new(read_half).lines();

    let reader = tokio::spawn(async move {
        while let Ok(Some(line)) = lines.next_line().await {
            if let Ok(msg) = serde_json::from_str::<ClientMsg>(&line) {
                let _ = tx_submit.send(msg);
            }
        }
    });

    loop {
        let snap = rx.borrow_and_update().clone();
        let mut json = match serde_json::to_string(&snap) {
            Ok(j) => j,
            Err(_) => break,
        };
        json.push('\n');
        if write_half.write_all(json.as_bytes()).await.is_err() {
            break;
        }
        if rx.changed().await.is_err() {
            break;
        }
    }
    reader.abort();
}

// --- main -------------------------------------------------------------------

#[tokio::main(flavor = "current_thread")]
async fn main() {
    let cli = Cli::parse();
    let state_file = state_file_for(&cli.socket);
    if let Err(e) = run(cli).await {
        let msg = format!("FAILED: {e:#}");
        eprintln!("operator-secrets: {msg}");
        let _ = std::fs::write(&state_file, format!("{msg}\n"));
        std::process::exit(1);
    }
}

async fn run(cli: Cli) -> Result<()> {
    let text = std::fs::read_to_string(&cli.spec)
        .with_context(|| format!("reading spec {}", cli.spec.display()))?;
    let spec = Spec::parse(&text).map_err(anyhow::Error::msg)?;

    // Fail before prompting, not after: an unknown owner discovered once
    // the operator has already typed a secret in is pure toil.
    let ids: Vec<Ids> = spec
        .secrets
        .iter()
        .map(resolve_ids)
        .collect::<Result<_>>()?;

    // Anyone who can reach this socket can answer a prompt — that is,
    // can choose what credential the host ends up trusting — and can read
    // every snapshot. Lock the directory down to root BEFORE binding, so
    // the socket is never reachable by anyone else even momentarily, then
    // narrow the socket itself for good measure.
    if let Some(dir) = cli.socket.parent() {
        prepare_socket_dir(dir)?;
    }
    let _ = std::fs::remove_file(&cli.socket);
    let listener = UnixListener::bind(&cli.socket).context("binding control socket")?;
    std::fs::set_permissions(&cli.socket, PermissionsExt::from_mode(0o600))
        .context("restricting control socket")?;

    let (tx, _) = watch::channel(Snapshot::default());
    let (tx_submit, rx_submit) = mpsc::unbounded_channel();
    let ui: &'static Ui = Box::leak(Box::new(Ui {
        state_file: state_file_for(&cli.socket),
        snapshot: Mutex::new(Snapshot::default()),
        tx,
        submissions: Mutex::new(rx_submit),
        next_prompt_id: Mutex::new(0),
    }));

    ui.mutate(|s| {
        s.secrets = spec
            .secrets
            .iter()
            .map(|x| SecretStatus {
                name: x.name.clone(),
                description: x.description.clone(),
                state: SecretState::Pending,
                detail: String::new(),
            })
            .collect();
    });

    // Accept TUI clients for the lifetime of the daemon.
    let rx_factory = ui.tx.subscribe();
    tokio::spawn(async move {
        loop {
            if let Ok((stream, _)) = listener.accept().await {
                tokio::spawn(serve_client(stream, rx_factory.clone(), tx_submit.clone()));
            }
        }
    });

    let timeout = Duration::from_secs(cli.validator_timeout_secs);
    let retry = Duration::from_secs(cli.retry_interval_secs);

    // ONE operator session for everything outstanding: the operator sees
    // the whole list and answers it in one sitting, rather than meeting a
    // fresh fullscreen prompt per consuming service.
    for (s, ids) in spec.secrets.iter().zip(&ids) {
        satisfy(ui, s, ids, timeout, retry).await?;
    }

    ui.mutate(|s| {
        s.done = true;
        s.blocked = false;
        s.prompt = None;
    });
    ui.state(
        "done",
        "all operator-provided secrets satisfied; boot continuing",
    );
    // Let connected clients render the final frame before the socket dies.
    tokio::time::sleep(Duration::from_millis(200)).await;
    let _ = std::fs::remove_file(&cli.socket);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vals(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    #[test]
    fn redaction_strips_values_from_validator_stderr() {
        // The case that matters: a third-party validator that dumps its
        // parsed request in a stack trace. The value must not survive into
        // the journal; the field NAME may, it is already public.
        let v = vals(&[
            ("CLIENT_ID", "app-123456"),
            ("CLIENT_SECRET", "hunter2secret"),
        ]);
        let stderr = "panic: ValidatorRequest { CLIENT_ID: \"app-123456\", \
                      CLIENT_SECRET: \"hunter2secret\" }";
        let out = redact_values(stderr, &v);
        assert!(!out.contains("hunter2secret"), "{out}");
        assert!(!out.contains("app-123456"), "{out}");
        assert!(out.contains("CLIENT_SECRET"), "{out}");
    }

    #[test]
    fn redaction_leaves_ordinary_diagnostics_alone() {
        let v = vals(&[("CLIENT_SECRET", "s3cr3tvalue")]);
        let msg = "connection refused reaching https://sso.example.com";
        assert_eq!(redact_values(msg, &v), msg);
        // Very short values would turn a diagnostic into confetti and
        // reveal little; they are deliberately left.
        assert_eq!(
            redact_values("abc happened", &vals(&[("K", "ab")])),
            "abc happened"
        );
    }

    #[test]
    fn socket_dir_is_created_private() {
        use std::os::unix::fs::PermissionsExt;
        let base = std::env::temp_dir().join(format!("opsec-test-{}", std::process::id()));
        let dir = base.join("sock-dir");
        prepare_socket_dir(&dir).unwrap();
        let mode = std::fs::metadata(&dir).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o700, "socket dir must be private to its owner");
        // Idempotent: a second run over our own already-private dir is fine.
        prepare_socket_dir(&dir).unwrap();
        let _ = std::fs::remove_dir_all(&base);
    }

    #[test]
    fn refuses_to_narrow_a_shared_directory() {
        // The foot-gun: --socket /run/x.sock would otherwise chmod /run to
        // 0700 and cut every non-root service off, wedging the boot with no
        // obvious cause. Refuse loudly instead.
        use std::os::unix::fs::PermissionsExt;
        let base = std::env::temp_dir().join(format!("opsec-shared-{}", std::process::id()));
        std::fs::create_dir_all(&base).unwrap();
        std::fs::set_permissions(&base, PermissionsExt::from_mode(0o755)).unwrap();
        let err = prepare_socket_dir(&base).unwrap_err().to_string();
        assert!(err.contains("refusing to narrow"), "{err}");
        // ...and it is left exactly as it was.
        let mode = std::fs::metadata(&base).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o755);
        let _ = std::fs::remove_dir_all(&base);
    }
}
