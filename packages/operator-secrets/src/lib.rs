    #[test]
    fn spec_accepts_missing_validate_command() {
        // Absent means "no external proof; presence of all fields decides".
        // An explicitly empty argv stays rejected (see spec_rejects_nonsense)
        // so a typo'd validator list cannot silently disable validation.
        let spec = Spec::parse(
            r#"{"version":1,"secrets":[{"name":"a","fields":[{"name":"K"}],"path":"/x"}]}"#,
        )
        .expect("spec without validate_command must parse");
        assert_eq!(spec.secrets[0].validate_command, None);
    }

    #[test]
    fn spec_rejects_nonsense() {
        let bad = [
            r#"{"version":2,"secrets":[]}"#,
            r#"{"version":1,"secrets":[{"name":"a","fields":[],"path":"/x","validate_command":["v"]}]}"#,
            r#"{"version":1,"secrets":[{"name":"a","fields":[{"name":"K"}],"path":"/x","validate_command":[]}]}"#,
            r#"{"version":1,"secrets":[{"name":"a","fields":[{"name":"K"}],"path":"rel","validate_command":["v"]}]}"#,
            r#"{"version":1,"secrets":[{"name":"a","fields":[{"name":"K"}],"path":"/x","mode":"rwx","validate_command":["v"]}]}"#,
            r#"{"version":1,"secrets":[{"name":"a","fields":[{"name":"bad key"}],"path":"/x","validate_command":["v"]}]}"#,
        ];
        for b in bad {
            assert!(Spec::parse(b).is_err(), "{b}");
        }
    }

