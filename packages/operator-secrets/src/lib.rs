//! Shared spec, wire protocol and the pure logic behind operator-secrets.
//!
//! The daemon (`operator-secretsd`) owns the state machine; TUI clients
//! (`operator-secrets-tui`) connect over a unix socket and receive
//! [`Snapshot`]s as newline-delimited JSON, sending [`ClientMsg`]s back —
//! the same split, and for the same reason, as `var-disk-manager`: the
//! console UI and any SSH session render one screen and any of them may
//! answer.
//!
//! Everything that can be decided without I/O lives here as a pure
//! function so the security-critical parts are unit-testable: env-file
//! encoding (a secret must never be mangled or shell-interpreted by its
//! consumer), stored-file classification (a half-written file must never
//! look satisfied), and validator-verdict parsing (a crashed validator
//! must never look like `invalid`).

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

pub const SOCKET_PATH: &str = "/run/operator-secrets/sock";

/// Control socket of an edit session — the daemon run on demand on a
/// running host to re-enter a secret that is already stored.
///
/// Deliberately not the boot socket, and deliberately in a directory of
/// its own: a boot that is still parked owns that socket and that
/// breadcrumb file, and an edit must not be able to take either from it.
pub const EDIT_SOCKET_PATH: &str = "/run/operator-secrets-edit/sock";

/// Unit an edit session runs as, started by the TUI when the operator asks
/// to edit. Neither side can discover this from the other, so the NixOS
/// module names its unit to match this constant.
pub const EDIT_UNIT: &str = "operator-secrets-edit.service";

/// Breadcrumb file carrying the current message line, for
/// `ssh host 'cat …'` scripting and for a client that connects after the
/// daemon is gone. It sits beside the socket so that pointing either
/// binary at a different `--socket` moves both consistently.
pub fn state_file_for(socket: &std::path::Path) -> std::path::PathBuf {
    match socket.parent() {
        Some(dir) if !dir.as_os_str().is_empty() => dir.join("state"),
        _ => std::path::PathBuf::from("state"),
    }
}

// --- spec (nix -> daemon) ---------------------------------------------------

/// The spec is generated by `services/operator-secrets.nix` from its
/// options and contains **no secret values** — only names, descriptions,
/// field lists, destinations and the validator argv. It is therefore safe
/// in the nix store, which is where it lives.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Spec {
    /// Schema version; the daemon refuses anything it does not know.
    pub version: u32,
    pub secrets: Vec<SecretSpec>,
}

pub const SPEC_VERSION: u32 = 1;

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct SecretSpec {
    /// Attribute name of the secret; the daemon's stable identifier.
    pub name: String,
    #[serde(default)]
    pub description: String,
    /// Ordered field list. Order is the order the TUI presents and the
    /// order `KEY=VALUE` lines are written in.
    pub fields: Vec<FieldSpec>,
    /// Destination env-file.
    pub path: String,
    #[serde(default = "default_owner")]
    pub owner: String,
    /// Defaults to `owner` when null (matching services/secrets.nix).
    #[serde(default)]
    pub group: Option<String>,
    #[serde(default = "default_mode")]
    pub mode: String,
    /// Validator argv: program plus its flags. A LIST, never a shell
    /// string — the values must not pass through a shell, and the daemon
    /// must never need one to spawn this.
    ///
    /// `None` means the secret has no external proof (e.g. ZeroSSL EAB
    /// credentials, where a real check would be a full ACME account dance):
    /// "all declared fields present and non-empty" is then the acceptance
    /// criterion, both for a stored file and for prompted input. Absent and
    /// `[]` are deliberately distinct — an accidentally empty argv is a
    /// config error, not a request for no validation.
    #[serde(default)]
    pub validate_command: Option<Vec<String>>,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct FieldSpec {
    /// Env-file key, e.g. `CLIENT_SECRET`.
    pub name: String,
    #[serde(default)]
    pub description: String,
    /// Only controls TUI echo and whether the value may be pre-filled
    /// into a re-prompt. It is NOT a confidentiality boundary: every
    /// field lands in the same file with the same mode.
    #[serde(default)]
    pub sensitive: bool,
}

fn default_owner() -> String {
    "root".into()
}

fn default_mode() -> String {
    "0400".into()
}

impl SecretSpec {
    pub fn group(&self) -> &str {
        self.group.as_deref().unwrap_or(&self.owner)
    }

    pub fn field(&self, name: &str) -> Option<&FieldSpec> {
        self.fields.iter().find(|f| f.name == name)
    }
}

impl Spec {
    pub fn parse(text: &str) -> Result<Self, String> {
        let spec: Spec = serde_json::from_str(text).map_err(|e| format!("parsing spec: {e}"))?;
        if spec.version != SPEC_VERSION {
            return Err(format!(
                "spec version {} unsupported (this daemon speaks {SPEC_VERSION})",
                spec.version
            ));
        }
        for s in &spec.secrets {
            if s.fields.is_empty() {
                return Err(format!("secret {}: no fields declared", s.name));
            }
            if s.validate_command.as_ref().is_some_and(|v| v.is_empty()) {
                return Err(format!(
                    "secret {}: empty validate_command (omit the key entirely for a \
                     presence-only secret)",
                    s.name
                ));
            }
            if !s.path.starts_with('/') {
                return Err(format!("secret {}: path must be absolute", s.name));
            }
            if parse_mode(&s.mode).is_none() {
                return Err(format!("secret {}: mode {:?} is not octal", s.name, s.mode));
            }
            for f in &s.fields {
                if !is_valid_key(&f.name) {
                    return Err(format!(
                        "secret {}: field name {:?} is not a valid env-file key",
                        s.name, f.name
                    ));
                }
            }
        }
        Ok(spec)
    }
}

/// Parse a `"0400"`-style mode. Rejects anything that is not octal or
/// wider than 12 bits, so a typo can never widen a secret's permissions.
pub fn parse_mode(mode: &str) -> Option<u32> {
    if mode.is_empty() || mode.len() > 5 || !mode.bytes().all(|b| (b'0'..=b'7').contains(&b)) {
        return None;
    }
    let v = u32::from_str_radix(mode, 8).ok()?;
    if v > 0o7777 { None } else { Some(v) }
}

pub fn is_valid_key(k: &str) -> bool {
    !k.is_empty()
        && !k.starts_with(|c: char| c.is_ascii_digit())
        && k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

// --- wire protocol ----------------------------------------------------------

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub enum SecretState {
    /// Not looked at yet.
    Pending,
    /// Reading / validating the stored file.
    Checking,
    /// Waiting for the operator.
    NeedsInput,
    /// Operator answered; validator running.
    Validating,
    /// Present and proven valid; nothing more to do.
    Satisfied,
    /// The validator could not decide. Never written, never discarded.
    Undecided,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct SecretStatus {
    pub name: String,
    pub description: String,
    pub state: SecretState,
    /// Human-readable detail. Never contains a field value.
    pub detail: String,
}

/// One outstanding secret, presented as a form. `value` carries a
/// pre-fill and is populated for NON-sensitive fields only — a sensitive
/// value must never travel back out of the daemon, because a snapshot
/// goes to every connected client.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct PromptField {
    pub name: String,
    pub description: String,
    pub sensitive: bool,
    pub value: String,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Prompt {
    pub id: u64,
    /// Secret name this prompt belongs to.
    pub secret: String,
    pub description: String,
    /// Why we are asking (absent file, failed validation, bad input).
    pub reason: String,
    pub fields: Vec<PromptField>,
}

/// Full UI state; the daemon sends a fresh one on every change. Contains
/// no secret values other than the non-sensitive pre-fills above.
#[derive(Serialize, Deserialize, Clone, Debug, Default)]
pub struct Snapshot {
    /// Short phase tag, e.g. `check`, `prompt`, `validate`, `undecided`.
    pub phase: String,
    /// One human-readable line; mirrored into the state file.
    pub message: String,
    /// The boot is parked and cannot proceed without operator action
    /// elsewhere (validator cannot decide).
    pub blocked: bool,
    pub secrets: Vec<SecretStatus>,
    pub prompt: Option<Prompt>,
    /// Set once every secret is satisfied and the daemon is exiting 0.
    pub done: bool,
    /// An edit session is waiting for the operator to choose which secret
    /// to re-enter. Never set during a boot, where the daemon decides what
    /// needs answering and the operator only answers it.
    #[serde(default)]
    pub choosing: bool,
}

#[derive(Serialize, Deserialize, Clone)]
pub enum ClientMsg {
    /// Answer to `prompt_id`. Ordered field name/value pairs; the daemon
    /// re-orders and completeness-checks against the spec regardless.
    Submit {
        prompt_id: u64,
        values: Vec<(String, String)>,
    },
    /// Re-enter `secret`, which is already stored and would otherwise be
    /// left alone. Honoured only by an edit session, and only while it is
    /// waiting for a choice — a boot decides for itself what to ask.
    Edit { secret: String },
}

/// Debug is written by hand, not derived, for every type that holds an
/// operator-supplied VALUE. Nothing prints these today, but `{:?}` is one
/// stray `dbg!` or `.context(format!("{msg:?}"))` away from putting a
/// secret in the journal — and the journal is precisely where this
/// mechanism promises a value never lands. Redacting here makes that
/// invariant structural instead of a convention every future edit has to
/// remember. Field NAMES are kept: they are what makes a diagnostic
/// useful, and they are already public in the nix store.
impl std::fmt::Debug for ClientMsg {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Submit { prompt_id, values } => {
                let names: Vec<&str> = values.iter().map(|(k, _)| k.as_str()).collect();
                f.debug_struct("Submit")
                    .field("prompt_id", prompt_id)
                    .field("fields", &names)
                    .field("values", &"<redacted>")
                    .finish()
            }
            // A secret NAME, which is already public in the nix store.
            Self::Edit { secret } => f.debug_struct("Edit").field("secret", secret).finish(),
        }
    }
}

// --- validator protocol -----------------------------------------------------

#[derive(Serialize, Deserialize, Clone)]
pub struct ValidatorRequest {
    pub fields: BTreeMap<String, String>,
}

/// See the note on `impl Debug for ClientMsg`: names, never values.
impl std::fmt::Debug for ValidatorRequest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let names: Vec<&str> = self.fields.keys().map(String::as_str).collect();
        f.debug_struct("ValidatorRequest")
            .field("fields", &names)
            .field("values", &"<redacted>")
            .finish()
    }
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum ValidatorStatus {
    Valid,
    Invalid,
    Error,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct ValidatorResponse {
    pub status: ValidatorStatus,
    #[serde(default)]
    pub message: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Verdict {
    pub status: ValidatorStatus,
    pub message: String,
}

impl Verdict {
    pub fn error(message: impl Into<String>) -> Self {
        Self {
            status: ValidatorStatus::Error,
            message: message.into(),
        }
    }

    pub fn valid() -> Self {
        Self {
            status: ValidatorStatus::Valid,
            message: String::new(),
        }
    }

    pub fn invalid(message: impl Into<String>) -> Self {
        Self {
            status: ValidatorStatus::Invalid,
            message: message.into(),
        }
    }
}

/// Turn a validator's stdout into a verdict.
///
/// `status` is authoritative, never the exit code — that is the caller's
/// job to ignore. Anything unparseable is `error`, NEVER `invalid`: this
/// is the distinction that stops a crashed validator or a transient
/// network failure from rewriting or discarding a good stored secret.
pub fn parse_validator_output(stdout: &str) -> Verdict {
    let trimmed = stdout.trim();
    if trimmed.is_empty() {
        return Verdict::error("validator produced no output");
    }
    match serde_json::from_str::<ValidatorResponse>(trimmed) {
        Ok(r) => Verdict {
            status: r.status,
            message: r.message.unwrap_or_default(),
        },
        Err(e) => Verdict::error(format!("validator output is not a verdict object: {e}")),
    }
}

// --- env-file encoding ------------------------------------------------------

/// Characters that need no quoting in a systemd `EnvironmentFile=` value
/// (and are equally safe if a consumer sources the file with `sh`).
fn is_bare_safe(v: &str) -> bool {
    !v.is_empty()
        && v.chars().all(|c| {
            c.is_ascii_alphanumeric()
                || matches!(c, '_' | '-' | '.' | '/' | ':' | '@' | '+' | ',' | '=' | '~')
        })
}

/// Encode one env-file value. Bare when unambiguous, otherwise
/// double-quoted with `\`, `"`, `$` and `` ` `` escaped — the form
/// systemd's parser and `sh` agree on. A value must never be able to
/// smuggle a second assignment or a command substitution into a consumer.
pub fn encode_env_value(v: &str) -> String {
    if is_bare_safe(v) {
        return v.to_string();
    }
    let mut out = String::with_capacity(v.len() + 2);
    out.push('"');
    for c in v.chars() {
        if matches!(c, '\\' | '"' | '$' | '`') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

/// Render the env-file body in spec field order.
pub fn encode_env_file(fields: &[(String, String)]) -> String {
    let mut out = String::new();
    for (k, v) in fields {
        out.push_str(k);
        out.push('=');
        out.push_str(&encode_env_value(v));
        out.push('\n');
    }
    out
}

/// Parse an env-file back into key/value pairs. Round-trips
/// [`encode_env_file`] and additionally tolerates the hand-written forms
/// (single quotes, comments, blank lines) an operator may have left
/// behind from the pre-mechanism status quo.
pub fn parse_env_file(text: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((k, v)) = line.split_once('=') else {
            continue;
        };
        let k = k.trim();
        if !is_valid_key(k) {
            continue;
        }
        out.insert(k.to_string(), decode_env_value(v.trim()));
    }
    out
}

fn decode_env_value(v: &str) -> String {
    let bytes: Vec<char> = v.chars().collect();
    match bytes.first() {
        Some('"') if bytes.len() >= 2 && bytes[bytes.len() - 1] == '"' => {
            let mut out = String::new();
            let mut it = bytes[1..bytes.len() - 1].iter().peekable();
            while let Some(&c) = it.next() {
                if c == '\\'
                    && let Some(&&n) = it.peek()
                {
                    it.next();
                    out.push(n);
                    continue;
                }
                out.push(c);
            }
            out
        }
        // Single quotes: literal, no escapes (as in sh and systemd).
        Some('\'') if bytes.len() >= 2 && bytes[bytes.len() - 1] == '\'' => {
            bytes[1..bytes.len() - 1].iter().collect()
        }
        _ => v.to_string(),
    }
}

/// Reject values that cannot be represented in an env-file, or that
/// would be silently mangled by a consumer. Applied to operator input
/// before anything is validated or written.
pub fn check_field_value(v: &str) -> Result<(), String> {
    if v.is_empty() {
        return Err("must not be empty".into());
    }
    if v.chars().any(|c| c.is_control()) {
        return Err("must not contain control characters or newlines".into());
    }
    Ok(())
}

// --- stored-file classification (pure) --------------------------------------

#[derive(Clone, PartialEq, Eq)]
pub enum StoredState {
    /// No file at all: prompt, validate, write, release.
    Absent,
    /// Every declared field present and representable: worth validating.
    Complete(Vec<(String, String)>),
    /// File exists but is unusable as-is (missing/blank/mangled field).
    /// Prompt without ever calling the validator — there is nothing
    /// coherent to validate.
    Incomplete {
        reason: String,
        usable: BTreeMap<String, String>,
    },
}

/// See the note on `impl Debug for ClientMsg`. This one holds the values
/// read back off disk, so it redacts too; test failures still show the
/// variant and which fields were present, which is what localises a bug.
impl std::fmt::Debug for StoredState {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Absent => f.write_str("Absent"),
            Self::Complete(values) => {
                let names: Vec<&str> = values.iter().map(|(k, _)| k.as_str()).collect();
                f.debug_tuple("Complete").field(&names).finish()
            }
            Self::Incomplete { reason, usable } => {
                let names: Vec<&str> = usable.keys().map(String::as_str).collect();
                f.debug_struct("Incomplete")
                    .field("reason", reason)
                    .field("usable", &names)
                    .finish()
            }
        }
    }
}

/// Classify the stored file against the spec. `None` is "file does not
/// exist" — the whole left-hand column of the state-machine table is
/// decided here, in one place.
///
/// Extra keys present in the file but not in the spec are dropped, not an
/// error: a field removed from the nix config must not park the boot.
pub fn classify_stored(
    spec: &SecretSpec,
    parsed: Option<&BTreeMap<String, String>>,
) -> StoredState {
    let Some(parsed) = parsed else {
        return StoredState::Absent;
    };
    let mut values = Vec::with_capacity(spec.fields.len());
    let mut usable = BTreeMap::new();
    let mut missing = Vec::new();
    for f in &spec.fields {
        match parsed.get(&f.name) {
            Some(v) if check_field_value(v).is_ok() => {
                usable.insert(f.name.clone(), v.clone());
                values.push((f.name.clone(), v.clone()));
            }
            Some(_) => missing.push(format!("{} (unusable value)", f.name)),
            None => missing.push(f.name.clone()),
        }
    }
    if missing.is_empty() {
        StoredState::Complete(values)
    } else {
        StoredState::Incomplete {
            reason: format!("stored file is incomplete: {}", missing.join(", ")),
            usable,
        }
    }
}

/// Build the prompt field list, pre-filling from `known` for NON-sensitive
/// fields only. Pre-filling a sensitive field would echo it back to every
/// connected client; re-typing it is the point.
pub fn prompt_fields(spec: &SecretSpec, known: &BTreeMap<String, String>) -> Vec<PromptField> {
    spec.fields
        .iter()
        .map(|f| PromptField {
            name: f.name.clone(),
            description: f.description.clone(),
            sensitive: f.sensitive,
            value: if f.sensitive {
                String::new()
            } else {
                known.get(&f.name).cloned().unwrap_or_default()
            },
        })
        .collect()
}

/// Check a submitted form against the spec: every declared field present
/// exactly once and representable. Returns the values in spec order.
pub fn accept_submission(
    spec: &SecretSpec,
    values: &[(String, String)],
) -> Result<Vec<(String, String)>, String> {
    let mut map: BTreeMap<&str, &str> = BTreeMap::new();
    for (k, v) in values {
        if spec.field(k).is_none() {
            return Err(format!("unknown field {k:?}"));
        }
        if map.insert(k.as_str(), v.as_str()).is_some() {
            return Err(format!("field {k:?} submitted twice"));
        }
    }
    let mut out = Vec::with_capacity(spec.fields.len());
    for f in &spec.fields {
        let Some(v) = map.get(f.name.as_str()) else {
            return Err(format!("{} is missing", f.name));
        };
        check_field_value(v).map_err(|e| format!("{}: {e}", f.name))?;
        out.push((f.name.clone(), (*v).to_string()));
    }
    Ok(out)
}

// --- passwd/group resolution ------------------------------------------------

/// Resolve a user or group name to an id against the given
/// `/etc/passwd`-shaped text (`name:x:id:...`). A plain number is
/// accepted as itself so a spec can bypass NSS entirely.
pub fn lookup_id(db: &str, name: &str) -> Option<u32> {
    if let Ok(n) = name.parse::<u32>() {
        return Some(n);
    }
    db.lines().find_map(|line| {
        let mut it = line.split(':');
        if it.next()? != name {
            return None;
        }
        it.next()?; // password placeholder
        it.next()?.parse().ok()
    })
}

