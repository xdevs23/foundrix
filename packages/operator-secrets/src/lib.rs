    // --- validator verdicts (the security-critical direction) ---

    #[test]
    fn verdict_parses_the_three_statuses() {
        for (json, want) in [
            (r#"{"status":"valid"}"#, ValidatorStatus::Valid),
            (
                r#"{"status":"invalid","message":"nope"}"#,
                ValidatorStatus::Invalid,
            ),
            (
                r#"{"status":"error","message":"dns"}"#,
                ValidatorStatus::Error,
            ),
        ] {
            assert_eq!(parse_validator_output(json).status, want, "{json}");
        }
        assert_eq!(
            parse_validator_output(r#"{"status":"invalid","message":"nope"}"#).message,
            "nope"
        );
        // Trailing newline / whitespace is normal from a line-buffered writer.
        assert_eq!(
            parse_validator_output("  {\"status\":\"valid\"}\n\n").status,
            ValidatorStatus::Valid
        );
    }

    #[test]
    fn garbage_is_error_never_invalid() {
        for junk in [
            "",
            "   ",
            "boom",
            "Traceback (most recent call last):",
            r#"{"status":"VALID"}"#,      // wrong case: not a status we know
            r#"{"status":"broken"}"#,     // unknown status word
            r#"{"message":"no status"}"#, // missing status
            r#"{"status":"valid"}{"status":"invalid"}"#, // two objects
            "null",
        ] {
            let v = parse_validator_output(junk);
            assert_eq!(v.status, ValidatorStatus::Error, "{junk:?} -> {v:?}");
        }
    }

    // --- env-file encoding ---

    #[test]
    fn plain_values_stay_bare() {
        assert_eq!(encode_env_value("abc123"), "abc123");
        assert_eq!(encode_env_value("forgejo-oidc.dev"), "forgejo-oidc.dev");
        assert_eq!(
            encode_env_value("https://sso.example.com/x"),
            "https://sso.example.com/x"
        );
        assert_eq!(encode_env_value("a+b=c,d~e@f"), "a+b=c,d~e@f");
    }

    #[test]
    fn dangerous_values_are_quoted_and_escaped() {
        // A value must not be able to smuggle a command substitution or a
        // second assignment into whatever consumes the file.
        assert_eq!(encode_env_value("a b"), "\"a b\"");
        assert_eq!(encode_env_value("$(id)"), r#""\$(id)""#);
        assert_eq!(encode_env_value("`id`"), r#""\`id\`""#);
        assert_eq!(encode_env_value(r#"he said "hi""#), r#""he said \"hi\"""#);
        assert_eq!(encode_env_value(r"back\slash"), r#""back\\slash""#);
        assert_eq!(encode_env_value("x\nY=evil"), "\"x\nY=evil\"");
        assert_eq!(encode_env_value(""), "\"\"");
    }

    #[test]
    fn env_file_roundtrips_every_awkward_value() {
        let awkward = [
            "simple",
            "with space",
            r#"quote" and \ backslash"#,
            "$(id) `id` ${HOME}",
            "'single'",
            "trailing ",
            " leading",
            "=starts-with-equals",
            "#not-a-comment",
            "ü-non-ascii-🔑",
        ];
        for v in awkward {
            let fields = vec![("CLIENT_SECRET".to_string(), v.to_string())];
            let text = encode_env_file(&fields);
            let back = parse_env_file(&text);
            assert_eq!(
                back.get("CLIENT_SECRET").map(String::as_str),
                Some(v),
                "{v:?} via {text:?}"
            );
        }
    }

